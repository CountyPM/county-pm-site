#!/usr/bin/env node
// stamp-faq-cache-key.mjs
// Durable fix for the stale-Vercel-build-cache bug (see
// claude/blog-spoke-stale-cache-2026-07-09.md).
//
// The blog pages read content/faq/*.md via `fs` at build time to render their
// "Related questions" spokes. Next.js does NOT track those fs reads as
// cache-invalidation inputs, so when FAQ content changes WITHOUT a blog file
// changing, Vercel reuses the stale prerendered blog HTML and the spokes never
// reach production until a cache-cleared redeploy.
//
// This script computes a stable hash over content/faq (sorted filenames +
// content) and writes it to a generated module lib/faq-cache-key.ts. That module
// is imported by app/blog/[slug]/page.tsx, so any FAQ content change changes the
// imported constant -> Next cache-misses the blog pages -> they regenerate with
// current spokes.
//
// Idempotent: if the computed key equals the one already in the file, nothing is
// written (so it won't create a spurious diff on no-op runs).
//
// Flags:
//   --print-changed  print the generated path if (and only if) it changed
//   --quiet          suppress the human summary

import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const ROOT = process.cwd()
const FAQ_DIR = path.join(ROOT, 'content', 'faq')
const OUT = path.join(ROOT, 'lib', 'faq-cache-key.ts')

const args = new Set(process.argv.slice(2))
const PRINT_CHANGED = args.has('--print-changed')
const QUIET = args.has('--quiet')

function computeKey() {
  const files = fs.existsSync(FAQ_DIR)
    ? fs
        .readdirSync(FAQ_DIR)
        .filter((f) => f.endsWith('.md'))
        .sort()
    : []
  const h = crypto.createHash('sha256')
  for (const f of files) {
    h.update(f)
    h.update('\0')
    h.update(fs.readFileSync(path.join(FAQ_DIR, f)))
    h.update('\0')
  }
  return h.digest('hex').slice(0, 16)
}

function currentKeyInFile() {
  if (!fs.existsSync(OUT)) return null
  const m = fs.readFileSync(OUT, 'utf8').match(/FAQ_CACHE_KEY\s*=\s*'([^']+)'/)
  return m ? m[1] : null
}

function main() {
  const key = computeKey()
  const existing = currentKeyInFile()

  if (existing === key) {
    if (!QUIET && !PRINT_CHANGED) console.log(`faq cache key unchanged (${key})`)
    return
  }

  const contents =
    '// AUTO-GENERATED by scripts/stamp-faq-cache-key.mjs — do not edit by hand.\n' +
    '// Hash of content/faq/*.md. Imported by app/blog/[slug]/page.tsx so that any\n' +
    '// FAQ content change invalidates the blog pages\u2019 Next.js build cache and the\n' +
    '// "Related questions" spokes regenerate. See claude/blog-spoke-stale-cache-*.md.\n' +
    `export const FAQ_CACHE_KEY = '${key}'\n`

  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, contents)

  if (PRINT_CHANGED) {
    process.stdout.write(path.relative(ROOT, OUT) + '\n')
  } else if (!QUIET) {
    console.log(`stamped faq cache key: ${existing ?? '(none)'} -> ${key}`)
  }
}

main()
